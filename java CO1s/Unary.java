

public class Unary {
    public static void main(String[] args){
        int a = 79;

        System.out.println("orginal ="+ a);
        System.out.println("post Increment ="+ a++);
        System.out.println("now ="+ a);

        System.out.println("pre Increment ="+ ++a);
        System.out.println("pre Decrement ="+ --a);
        System.out.println("now ="+ a);
        
        
    }
}
